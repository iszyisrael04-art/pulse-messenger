begin;
create temporary table session_fixture(k text primary key,id uuid default gen_random_uuid());
insert into session_fixture(k)values('user'),('other'),('valid'),('expired'),('foreign');
grant select on session_fixture to authenticated;
insert into auth.users(id,aud,role,email,email_confirmed_at)select id,'authenticated','authenticated','session-'||id||'@example.invalid',now()from session_fixture where k in('user','other');
insert into auth.sessions(id,user_id,not_after)select s.id,u.id,case when s.k='expired'then now()-interval '1 second'else now()+interval '1 hour'end from session_fixture s,session_fixture u where(s.k in('valid','expired')and u.k='user')or(s.k='foreign'and u.k='other');
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from session_fixture where k='user'),'role','authenticated','session_id',(select id from session_fixture where k='valid'))::text,true);
set local role authenticated;
select public.pulse_wallet();
reset role;
delete from auth.sessions where id=(select id from session_fixture where k='valid');
set local role authenticated;
do $$begin
 begin perform public.pulse_wallet();raise exception 'FAIL revoked session used wallet';exception when others then if sqlerrm='FAIL revoked session used wallet'then raise;end if;end;
end $$;
