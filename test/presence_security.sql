begin;
create temporary table presence_fixture(k text primary key,id uuid default gen_random_uuid());
insert into presence_fixture(k) values('a'),('b'),('stranger'),('device1'),('device2'),('chat');
grant select on presence_fixture to authenticated;
insert into auth.users(id,aud,role,email,email_confirmed_at) select id,'authenticated','authenticated','presence-test-'||id||'@example.invalid',now() from presence_fixture where k in('a','b','stranger');
insert into public.pulse_chats(id,kind,name,owner_id,direct_key) select c.id,'direct','Presence fixture',a.id,'presence-'||c.id from presence_fixture c cross join presence_fixture a where c.k='chat' and a.k='a';
insert into public.pulse_members(chat_id,user_id,role) select c.id,u.id,'member' from presence_fixture c cross join presence_fixture u where c.k='chat' and u.k in('a','b');
update public.pulse_chat_requests set state='accepted' where chat_id=(select id from presence_fixture where k='chat');
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='a'),'role','authenticated')::text,true);
set local role authenticated;
select public.pulse_presence_tick((select id from presence_fixture where k='device1'),1,true);
select public.pulse_presence_tick((select id from presence_fixture where k='device2'),1,true);
select public.pulse_presence_tick((select id from presence_fixture where k='device1'),2,false);
-- A late, older heartbeat cannot resurrect a closed device.
select public.pulse_presence_tick((select id from presence_fixture where k='device1'),1,true);
reset role;
do $$begin
 if exists(select 1 from pulse_private.presence_devices where device_id=(select id from presence_fixture where k='device1') and expires_at>clock_timestamp()) then raise exception 'FAIL: out-of-order heartbeat';end if;
 if exists(select 1 from pulse_private.presence_devices where user_id<>(select id from presence_fixture where k='a') and device_id in(select id from presence_fixture where k like 'device%')) then raise exception 'FAIL: foreign heartbeat';end if;
end $$;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='b'),'role','authenticated')::text,true);
set local role authenticated;
do $$begin
 if public.pulse_presence_info(array[(select id from presence_fixture where k='a')])->0->>'online' is distinct from 'true' then raise exception 'FAIL: second device online';end if;
 if has_table_privilege('authenticated','pulse_private.presence_devices','SELECT') or has_table_privilege('authenticated','pulse_private.presence_devices','UPDATE') then raise exception 'FAIL: direct presence table access';end if;
 if has_function_privilege('anon','public.pulse_presence_info(uuid[])','EXECUTE') then raise exception 'FAIL: anonymous presence access';end if;
end $$;
reset role;
update public.pulse_chat_requests set state='pending' where chat_id=(select id from presence_fixture where k='chat');
set local role authenticated;
do $$begin if jsonb_array_length(public.pulse_presence_info(array[(select id from presence_fixture where k='a')]))<>0 then raise exception 'FAIL: pending request exposed status';end if;end $$;
reset role;
delete from public.pulse_chat_requests where chat_id=(select id from presence_fixture where k='chat');
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='stranger'),'role','authenticated')::text,true);
set local role authenticated;
do $$begin if jsonb_array_length(public.pulse_presence_info(array[(select id from presence_fixture where k='a')]))<>0 then raise exception 'FAIL: stranger presence leak';end if;end $$;
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='a'),'role','authenticated')::text,true);
set local role authenticated;
select public.pulse_presence_sharing(false);
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='b'),'role','authenticated')::text,true);
set local role authenticated;
do $$begin if jsonb_array_length(public.pulse_presence_info(array[(select id from presence_fixture where k='a')]))<>0 then raise exception 'FAIL: hidden last seen or online leaked';end if;end $$;
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='a'),'role','authenticated')::text,true);
set local role authenticated;
select public.pulse_presence_sharing(true);
reset role;
insert into public.pulse_blocks(user_id,blocked_id) select a.id,b.id from presence_fixture a cross join presence_fixture b where a.k='a' and b.k='b';
select set_config('request.jwt.claims',jsonb_build_object('sub',(select id from presence_fixture where k='b'),'role','authenticated')::text,true);
set local role authenticated;
do $$begin if jsonb_array_length(public.pulse_presence_info(array[(select id from presence_fixture where k='a')]))<>0 then raise exception 'FAIL: blocked presence leaked';end if;end $$;
reset role;
delete from public.pulse_blocks where user_id=(select id from presence_fixture where k='a');
update pulse_private.presence_devices set expires_at=now()-interval '1 second' where user_id=(select id from presence_fixture where k='a');
set local role authenticated;
do $$begin
 if public.pulse_presence_info(array[(select id from presence_fixture where k='a')])->0->>'online' is distinct from 'false' then raise exception 'FAIL: stale device online';end if;
 if public.pulse_presence_info(array[(select id from presence_fixture where k='a')])->0->>'last_seen' is null then raise exception 'FAIL: no last seen';end if;
end $$;
reset role;
rollback;
