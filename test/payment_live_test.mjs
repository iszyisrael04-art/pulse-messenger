import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {liveEnabled,liveCheckoutUrl,liveMatches,webhookValid} from '../supabase/functions/pulse-payments/live.mjs';
assert(!liveEnabled('sandbox_sk_example',()=> 'live'));
assert(!liveEnabled('sk_example',n=>n==='SQUAD_MODE'?'live':'false'));
assert(liveEnabled('sk_example',n=>n==='SQUAD_MODE'?'live':'true'));
assert.equal(liveCheckoutUrl('https://pay.squadco.com/abc'),'https://pay.squadco.com/abc');
assert.equal(liveCheckoutUrl('https://pay.squadco.com.evil.test/abc'),null);
const order={id:'order',currency:'USD',usd_cents:100};
const response={transaction_ref:'order',transaction_currency_id:'USD',transaction_amount:100,transaction_status:'Success'};
assert(liveMatches(response,order));
for(const patch of [{transaction_amount:1},{transaction_amount:'100'},{transaction_currency_id:'NGN'},{transaction_ref:'another'},{transaction_status:'Pending'}])assert(!liveMatches({...response,...patch},order));
const key='fixture-only',raw='{"Event":"charge_successful"}';
const k=await webcrypto.subtle.importKey('raw',new TextEncoder().encode(key),{name:'HMAC',hash:'SHA-512'},false,['sign']);
const hash=Buffer.from(await webcrypto.subtle.sign('HMAC',k,new TextEncoder().encode(raw))).toString('hex');
assert(await webhookValid(raw,hash,key));
assert(!await webhookValid(raw+' ',hash,key));
assert(!await webhookValid(raw,'bad',key));
console.log('PASS live mode gate, allowlisted URLs, signed webhooks and exact receipt matching');

const {checkoutFailure}=await import('../supabase/functions/pulse-payments/errors.mjs');
assert.equal(checkoutFailure(401,false,null).code,'squad_key_rejected');
assert.equal(checkoutFailure(403,false,null).code,'squad_access_denied');
assert.equal(checkoutFailure(429,false,null).code,'squad_rate_limit');
assert.equal(checkoutFailure(502,false,null).code,'squad_unavailable');
assert.equal(checkoutFailure(400,false,null).code,'squad_checkout_rejected');
assert.equal(checkoutFailure(200,true,null).code,'squad_checkout_address');
assert.equal(checkoutFailure(200,true,'https://pay.squadco.com/abc'),null);
console.log('PASS safe checkout error classification without exposing provider payloads');
